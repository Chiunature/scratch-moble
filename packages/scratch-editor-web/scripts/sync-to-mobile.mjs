import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packageRoot = path.resolve(__dirname, '..');
const repoRoot = path.resolve(packageRoot, '..', '..');

const distHtmlPath = path.join(packageRoot, 'dist', 'index.html');
const outputDir = path.join(repoRoot, 'apps', 'mobile', 'src', 'editor');
const outputFile = path.join(outputDir, 'editorBundleHtml.ts');

const html = await readFile(distHtmlPath, 'utf8');
const escaped = JSON.stringify(html);

const fileContent = `// Auto-generated by packages/scratch-editor-web/scripts/sync-to-mobile.mjs
// Do not edit manually.
export const EDITOR_BUNDLE_HTML = ${escaped};
`;

await mkdir(outputDir, { recursive: true });
await writeFile(outputFile, fileContent, 'utf8');

console.log('editor bundle synced to apps/mobile/src/editor/editorBundleHtml.ts');
